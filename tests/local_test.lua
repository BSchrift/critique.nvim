H.test("the agent's code changes and replies show up after it submits", function()
  local root, id = setup()
  open(id)
  goto_line(4)
  critique('comment')
  write_comment('Remove + 0')
  local input = vim.ui.input
  vim.ui.input = function(_, cb) cb('') end
  critique('submit', "the agent's turn")
  vim.ui.input = input
  -- The agent: fixes the code (adds a line above, too), replies, resolves, submits.
  local fixed = vim.deepcopy(CODE)
  table.insert(fixed, 1, '// Package cart adds things.')
  H.write(root, 'cart/cart.go', fixed)
  H.run(root, { 'reply', '1', 'Done.', '--as', 'claude' })
  H.run(root, { 'resolve', '1', '--as', 'claude' })
  local before = #messages
  H.run(root, { 'submit', '--as', 'claude' })
  H.wait_for(function()
    for i = before + 1, #messages do if messages[i].msg:find('claude submitted', 1, true) then return true end end
  end, 'the submit notification')
  H.eq(vim.api.nvim_buf_get_lines(0, 0, 1, false), { '// Package cart adds things.' }, 'buffer reloaded from disk')
  local qf = vim.tbl_map(function(q) return q.text end, vim.fn.getqflist())
  H.ok(vim.tbl_contains(qf, 'M  +1 -0'), 'diff recomputed: ' .. vim.inspect(qf))
  H.eq(thread_texts(), { { 4, ' ✓ #1 (2) · outdated · Tester: Remove + 0', 'CritiqueResolved' } },
    'the code is gone: the thread stays where it was, marked outdated, with the reply')
end)
