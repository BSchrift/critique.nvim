H.section('the loop with the agent')
H.test("the agent's threads appear when it submits, and you can reply", function()
  local root, id, log = setup()
  open(id)
  H.run(root, { 'comment', 'cart/cart.go:4', 'I added + 0 on purpose.', '--as', 'claude' })
  vim.wait(800)
  H.eq(thread_texts(), {}, 'agent drafts stay hidden')
  local before = #messages
  H.run(root, { 'submit', '--summary', 'Ready for review', '--as', 'claude' })
  H.wait_for(function()
    for i = before + 1, #messages do if messages[i].msg:find('claude submitted', 1, true) then return true end end
  end, 'the submit notification')
  H.has(last_msg(), 'claude submitted: Ready for review · your turn')
  H.eq(thread_texts(), { { 4, ' 💬 #1 (1) · claude: I added + 0 on purpose.', 'CritiqueThread' } })
  goto_line(4)
  critique('comment')
  local buf = table.concat(vim.api.nvim_buf_get_lines(0, 0, -1, false), '\n')
  H.has(buf, '<!-- @claude -->\nI added + 0 on purpose.')
  write_comment('Please remove it.')
  local t = store.load(log, 'human').threads[1]
  H.eq(vim.tbl_map(function(c) return c.author .. ': ' .. c.body end, t.comments), { 'claude: I added + 0 on purpose.', 'Tester: Please remove it.' })
end)
