local ns_diff = vim.api.nvim_create_namespace('critique.diff')
local ns_threads = vim.api.nvim_create_namespace('critique.threads')
local CODE = { 'package cart', '', 'func Add(a, b int) int {', '\treturn a + b', '}', '', 'func Sub(a, b int) int {', '\treturn a - b', '}' }

local messages = {}
vim.notify = function(msg, level) table.insert(messages, { msg = msg, level = level }) end
local function last_msg() return (messages[#messages] or {}).msg or '' end
local function errors_since(n)
  return vim.tbl_filter(function(m) return m.level == vim.log.levels.ERROR end, vim.list_slice(messages, n + 1))
end

-- Run a :Critique command and wait for a message containing `expect` (fails on an error message instead).
local function critique(args, expect)
  local before = #messages
  vim.cmd('Critique ' .. args)
  if expect then
    H.wait_for(function()
      for i = before + 1, #messages do
        if messages[i].msg:find(expect, 1, true) or messages[i].level == vim.log.levels.ERROR then return true end
      end
    end, expect)
  end
  local errs = errors_since(before)
  if #errs > 0 then error(':Critique ' .. args .. ' failed: ' .. errs[1].msg, 2) end
end

-- The error a :Critique command reports.
local function critique_error(args)
  local before = #messages
  vim.cmd('Critique ' .. args)
  H.wait_for(function() return #errors_since(before) > 0 end, 'an error from :Critique ' .. args)
  return errors_since(before)[1].msg
end

local function reset()
  vim.cmd('silent! only')
  vim.cmd('silent! %bwipeout!')
end

-- A repo with a committed file, an uncommitted change and a new untracked file, and a review the agent started.
local function setup()
  reset()
  local root = H.repo({ ['cart/cart.go'] = CODE, ['README.md'] = { '# shop', '', 'Sells things.' } })
  local changed = vim.deepcopy(CODE)
  changed[4] = '\treturn a + b + 0'
  H.write(root, 'cart/cart.go', changed)
  H.write(root, 'cart/new.go', { 'package cart', '', 'var Fee = 5' })
  local id = H.start(root, { '--title', 'Cart fix', '--base', 'HEAD', '--as', 'claude' })
  return root, id, (store.find(id, root))
end

local function open(handle)
  critique('open ' .. handle, ' changed · ')
end

-- Write `text` below the ▼ line of the open comment buffer and :w it.
local function write_comment(text, expect)
  local lines = vim.api.nvim_buf_get_lines(0, 0, -1, false)
  local at = vim.iter(ipairs(lines)):find(function(_, l) return l:find('▼ write below', 1, true) end)
  H.ok(at, 'not in a comment buffer: ' .. vim.api.nvim_buf_get_name(0))
  vim.api.nvim_buf_set_lines(0, at, -1, false, vim.split(text, '\n'))
  local before = #messages
  vim.cmd('write')
  H.wait_for(function() return #messages > before end, 'a message after :w')
  H.has(last_msg(), expect or 'saved')
  vim.cmd('quit')
end

local function marks(ns)
  return vim.api.nvim_buf_get_extmarks(0, ns, 0, -1, { details = true })
end
local function thread_texts()
  return vim.tbl_map(function(m) return { m[2] + 1, m[4].virt_text[1][1], m[4].virt_text[1][2] } end, marks(ns_threads))
end
local function goto_line(n) vim.api.nvim_win_set_cursor(0, { n, 0 }) end

