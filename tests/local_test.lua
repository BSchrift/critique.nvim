  H.ok(vim.iter(marks(ns_diff)):any(function(m) return m[4].line_hl_group == 'CritiqueAdd' and m[2] == 3 end), 'added line highlighted')
  H.ok(vim.iter(marks(ns_diff)):any(function(m) return m[4].virt_lines and m[4].virt_lines[1][1][1]:find('return a %+ b') end), 'deleted line shown')
