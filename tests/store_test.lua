H.test('a hostile global git config does not change the diff', function()
  local root = H.repo({ ['a.txt'] = { 'a', 'b', 'c', 'd', 'e', 'f', 'g', 'h', 'i', 'j' }, ['ren.txt'] = { 'same', 'content', 'here', 'x' } })
  local log = store.start(root, { title = 'x', base = 'HEAD' })
  H.write(root, 'a.txt', { 'a', 'b', 'c', 'd', 'E', 'f', 'g', 'h', 'i', 'j' })
  H.git(root, 'mv', 'ren.txt', 'moved.txt')
  H.write(root, 'café.txt', { 'c' })
  local clean = store.diff(store.load(log, 'agent'))
  local cfg = vim.env.GIT_CONFIG_GLOBAL
  vim.fn.writefile(vim.list_extend(vim.fn.readfile(cfg), { '[color]', '  ui = always', '[diff]', '  noprefix = true',
    '  mnemonicPrefix = true', '  renames = false', '  algorithm = histogram', '  context = 10', '[core]', '  quotepath = true' }),
    H.tmp .. '/hostile.gitconfig')
  vim.env.GIT_CONFIG_GLOBAL = H.tmp .. '/hostile.gitconfig'
  local ok, hostile = pcall(store.diff, store.load(log, 'agent'))
  vim.env.GIT_CONFIG_GLOBAL = cfg
  assert(ok, hostile)
  H.eq(hostile, clean)
  local files = diff.parse(hostile)
  local got = vim.tbl_map(function(f) return f.status .. ' ' .. f.path end, files)
  table.sort(got)
  H.eq(got, { 'A café.txt', 'M a.txt', 'R moved.txt' })
  H.eq(files[vim.iter(ipairs(files)):find(function(_, f) return f.path == 'a.txt' end)].hunks[1].old_count, 7, '3 lines of context')
end)


