H.section('a base that is not HEAD (coverage review)')
-- The agent commits after starting, so base, HEAD and the working tree all differ.
local function committed_review()
  local root = H.repo({ ['f.txt'] = { 'base one', 'base two', 'base three' } })
  local log = store.start(root, { title = 'x', base = 'HEAD' })
  H.write(root, 'f.txt', { 'head one', 'head two', 'head three' })
  H.git(root, 'commit', '-qam', 'agent work')
  H.write(root, 'f.txt', { 'work one', 'work two', 'work three' })
  return root, log
end
H.test('old-side lines come from the base commit, not HEAD', function()
  local root, log = committed_review()
  local r = store.load(log, 'agent')
  H.eq(store.file_lines(r, 'f.txt', 'old'), { 'base one', 'base two', 'base three' })
  H.eq(store.file_lines(r, 'f.txt', 'new'), { 'work one', 'work two', 'work three' })
end)
H.test('the diff covers base to working tree across the commit', function()
  local root, log = committed_review()
  local out = store.diff(store.load(log, 'agent'))
  H.has(out, '-base two')
  H.has(out, '+work two')
  H.lacks(out, 'head two')
end)

H.section('renames (coverage review)')
