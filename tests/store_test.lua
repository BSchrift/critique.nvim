H.test('the current path of a renamed file maps to its base path and back', function()
  local _, log = renamed_review()
  local r = store.load(log, 'agent')
  H.eq({ store.base_path(r, 'new.txt'), store.current_path(r, 'old.txt'), store.current_path(r, 'other.txt') },
    { 'old.txt', 'new.txt', 'other.txt' })
end)
