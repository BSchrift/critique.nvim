H.section('diff')
H.test('covers tracked changes, staged changes, and untracked files', function()
  local root = H.repo({ ['a.txt'] = { 'a' }, ['b.txt'] = { 'b' } })
  local log = store.start(root, { title = 'x', base = 'HEAD' })
  H.write(root, 'a.txt', { 'A' })
  H.write(root, 'b.txt', { 'B' })
  H.git(root, 'add', 'b.txt')
  H.write(root, 'dir/new.txt', { 'new' })
  local files = diff.parse(store.diff(store.load(log, 'agent')))
  local got = vim.tbl_map(function(f) return f.status .. ' ' .. f.path end, files)
  table.sort(got)
  H.eq(got, { 'A dir/new.txt', 'M a.txt', 'M b.txt' })
end)
H.test('includes committed work since the base', function()
  local root = H.repo({ ['a.txt'] = { 'a' } })
  local log = store.start(root, { title = 'x', base = 'HEAD' })
  H.write(root, 'a.txt', { 'committed' })
  H.git(root, 'commit', '-qam', 'work')
  H.eq(diff.parse(store.diff(store.load(log, 'agent')))[1].adds, 1)
end)
H.test('scope limits the diff to those paths', function()
  local root = H.repo({ ['src/a.txt'] = { 'a' }, ['other/b.txt'] = { 'b' } })
  local log = store.start(root, { title = 'x', base = 'HEAD', scope = { 'src' } })
  H.write(root, 'src/a.txt', { 'A' })
  H.write(root, 'other/b.txt', { 'B' })
  H.write(root, 'src/new.txt', { 'n' })
  H.write(root, 'other/new.txt', { 'n' })
  local got = vim.tbl_map(function(f) return f.path end, diff.parse(store.diff(store.load(log, 'agent'))))
  table.sort(got)
  H.eq(got, { 'src/a.txt', 'src/new.txt' })
end)
H.test('never includes the review files themselves', function()
  local root = H.repo()
  local log = store.start(root, { title = 'x', base = 'HEAD' })
  H.eq(diff.parse(store.diff(store.load(log, 'agent'))), {})
