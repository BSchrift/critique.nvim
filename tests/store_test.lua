H.section('relocate')
H.test('finds code where it was', function()
  H.eq(store.relocate({ 'a', 'b', 'c' }, { 'b' }, 2), 2)
end)
H.test('follows code that moved', function()
  H.eq(store.relocate({ 'new', 'new', 'a', 'b', 'c' }, { 'b' }, 2), 4)
end)
H.test('follows a multi-line block (returns its last line)', function()
  H.eq(store.relocate({ 'x', 'a', 'b', 'c' }, { 'a', 'b' }, 2), 3)
end)
H.test('picks the nearest match when the code repeats', function()
  H.eq(store.relocate({ 'b', 'x', 'x', 'x', 'x', 'b', 'x' }, { 'b' }, 5), 6)
  H.eq(store.relocate({ 'b', 'x', 'x', 'x', 'x', 'b', 'x' }, { 'b' }, 2), 1)
end)
H.test('returns nil when the code is gone', function()
  H.eq(store.relocate({ 'a', 'c' }, { 'b' }, 2), nil)
  H.eq(store.relocate({}, { 'b' }, 1), nil)
end)
H.test('handles a line past the end of a shorter file', function()
  H.eq(store.relocate({ 'b' }, { 'b' }, 9), 1)
end)

