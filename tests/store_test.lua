H.section('load')
local function new_review(files)
  local root = H.repo(files or { ['f.txt'] = { 'one', 'two', 'three' } })
  return root, store.start(root, { title = 'x' })
end
local function comment(log, fields)
  local id = store.new_id()
  store.append(log, vim.tbl_extend('force', { type = 'comment', id = id, thread = id, author = 'a', role = 'agent',
    path = 'f.txt', side = 'new', line = 2, code = { 'two' }, body = 'hi' }, fields or {}))
  return id
end

H.test('threads are numbered in order and replies attach to them', function()
  local _, log = new_review()
  local t1 = comment(log, { body = 'first' })
  comment(log, { body = 'second', line = 3, code = { 'three' } })
  store.append(log, { type = 'comment', id = store.new_id(), thread = t1, author = 'b', role = 'agent', body = 'reply' })
  local r = store.load(log, 'agent')
  H.eq(vim.tbl_map(function(t) return { t.n, #t.comments } end, r.threads), { { 1, 2 }, { 2, 1 } })
  H.eq(r.threads[1].comments[2].body, 'reply')
end)
H.test("the other side's drafts are hidden until submitted", function()
  local _, log = new_review()
  comment(log, { role = 'agent' })
  H.eq(#store.load(log, 'human').threads, 0, 'human must not see agent drafts')
  H.eq(store.load(log, 'agent').threads[1].comments[1].pending, true, 'agent sees its own draft')
  store.append(log, { type = 'submit', author = 'a', role = 'agent' })
  local c = store.load(log, 'human').threads[1].comments[1]
  H.eq(c.pending, false)
end)
H.test("a submit only publishes that side's drafts", function()
  local _, log = new_review()
  comment(log, { role = 'human', author = 'me' })
  store.append(log, { type = 'submit', author = 'a', role = 'agent' })
  H.eq(#store.load(log, 'agent').threads, 0)
  store.append(log, { type = 'submit', author = 'me', role = 'human' })
  H.eq(#store.load(log, 'agent').threads, 1)
end)
H.test('edit replaces the body; delete hides the comment', function()
  local _, log = new_review()
  local t = comment(log)
  local reply = store.new_id()
  store.append(log, { type = 'comment', id = reply, thread = t, author = 'a', role = 'agent', body = 'reply' })
  store.append(log, { type = 'edit', id = t, body = 'edited' })
  store.append(log, { type = 'delete', id = reply })
  H.eq(vim.tbl_map(function(c) return c.body end, store.load(log, 'agent').threads[1].comments), { 'edited' })
end)
H.test('deleting the first comment keeps the thread while replies remain', function()
  local _, log = new_review()
  local t = comment(log)
  store.append(log, { type = 'comment', id = store.new_id(), thread = t, author = 'a', role = 'agent', body = 'reply' })
  store.append(log, { type = 'delete', id = t })
  local r = store.load(log, 'agent')
  H.eq({ #r.threads, r.threads[1].line, r.threads[1].comments[1].body }, { 1, 2, 'reply' })
end)
H.test('a thread with every comment deleted disappears', function()
  local _, log = new_review()
  store.append(log, { type = 'delete', id = comment(log) })
  H.eq(#store.load(log, 'agent').threads, 0)
end)
H.test('resolve and unresolve', function()
  local _, log = new_review()
  local t = comment(log)
  store.append(log, { type = 'resolve', thread = t, resolved = true, role = 'human' })
  H.eq(store.load(log, 'agent').threads[1].resolved, true)
  store.append(log, { type = 'resolve', thread = t, resolved = false, role = 'human' })
  H.eq(store.load(log, 'agent').threads[1].resolved, false)
