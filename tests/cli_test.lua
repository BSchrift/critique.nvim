local function watch_output(root, act, settle)
  local out, done = {}, false
  vim.system({ H.bin, 'watch', '--settle', settle or '0' }, { cwd = root, stdout = function(_, d) if d then table.insert(out, d) end end },
    function() done = true end)
  vim.wait(1500)
  act()
  vim.wait(2500)
  return table.concat(out), function() H.wait_for(function() return done end, 'watch to exit', 10000) end
end
H.test('watch reports edits and live mode changes, never the agent itself, and nothing from before it started', function()
  local root, _, log = live_setup()
