H.test('wait holds while the human keeps saving, then returns once they are quiet', function()
  local root, _, log = live_setup()
  local result, t0 = nil, vim.uv.hrtime()
  local elapsed = function() return (vim.uv.hrtime() - t0) / 1e9 end
  vim.system({ H.bin, 'wait', '--settle', '3', '--timeout', '30' }, { cwd = root }, function(r) result = r end)
  for _, at in ipairs({ 0.5, 2.5, 4.5 }) do
    vim.wait(math.max(0, (at - elapsed()) * 1000))
    human_comment(log, { line = 8, code = { '\treturn a - b' }, body = 'comment at ' .. at })
  end
  vim.wait(math.max(0, (6.0 - elapsed()) * 1000))
  H.eq(result, nil, 'returned while the human was still saving')
  H.wait_for(function() return result ~= nil end, 'wait to return', 8000)
  H.ok(elapsed() >= 6.5, 'returned too early: ' .. elapsed())
  H.has(result.stdout, 'comment at 4.5')
end)
H.test('watch holds lines until the human is quiet, then sends them as one batch', function()
  local root, _, log = live_setup()
  local chunks, done = {}, false
  vim.system({ H.bin, 'watch', '--settle', '3' }, { cwd = root, stdout = function(_, d) if d then table.insert(chunks, { vim.uv.hrtime(), d }) end end },
    function() done = true end)
  vim.wait(1500)
  local t0 = vim.uv.hrtime()
  human_comment(log, { body = 'one' })
  vim.wait(1000)
  human_comment(log, { line = 8, code = { '\treturn a - b' }, body = 'two' })
  H.wait_for(function() return table.concat(vim.tbl_map(function(c) return c[2] end, chunks)):find('two', 1, true) end, 'the batch', 12000)
  local first_at = chunks[1][1]
  H.ok((first_at - t0) / 1e9 >= 3, 'printed before the human was quiet')
  local all = table.concat(vim.tbl_map(function(c) return c[2] end, chunks))
  H.has(all, 'one')
  local _, trailers = all:gsub('%(critique list %-r', '')
  H.eq(trailers, 1, 'one trailer for the batch')
  human(log, { type = 'close' })
  H.wait_for(function() return done end, 'watch to exit', 10000)
end)
