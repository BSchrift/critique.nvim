-- Integration tests for the `critique` CLI (what agents use), run as real subprocesses in temp repos. Offline.
-- Run: nvim --headless -l tests/cli_test.lua
local H = dofile(vim.fn.fnamemodify(debug.getinfo(1, 'S').source:sub(2), ':p:h') .. '/helpers.lua')
local store = require('critique.store')

local CODE = { 'package cart', '', 'func Add(a, b int) int {', '\treturn a + b', '}', '', 'func Sub(a, b int) int {', '\treturn a - b', '}' }

-- A repo with a committed file, then an uncommitted change and a review started by the agent.
local function setup(title)
  local root = H.repo({ ['cart/cart.go'] = CODE, ['README.md'] = { '# shop' } })
  local changed = vim.deepcopy(CODE)
  changed[4] = '\treturn a + b + 0'
  H.write(root, 'cart/cart.go', changed)
  local id = H.start(root, { '--title', title or 'Cart fix', '--base', 'HEAD', '--as', 'claude' })
  return root, id, (store.find(id, root))
end

-- What the human does in Neovim, written straight to the log.
local function human(log, ev)
  return store.append(log, vim.tbl_extend('keep', ev, { author = 'Tester', role = 'human' }))
end
local function human_comment(log, fields)
  local id = store.new_id()
  human(log, vim.tbl_extend('force', { type = 'comment', id = id, thread = id, path = 'cart/cart.go', side = 'new',
    line = 4, code = { '\treturn a + b + 0' }, body = 'Why + 0?' }, fields or {}))
  return id
end

