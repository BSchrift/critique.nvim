H.test('wait wakes up when the human submits', function()
  local root, _, log = setup()
  H.run(root, { 'submit' })
  local result
  vim.system({ H.bin, 'wait', '--timeout', '20' }, { cwd = root }, function(r) result = r end)
  vim.wait(1500)
  H.eq(result, nil, 'wait returned before the human submitted')
  human_comment(log, { body = 'late feedback' })
  human(log, { type = 'submit' })
  H.wait_for(function() return result ~= nil end, 'wait to return', 10000)
  H.eq(result.code, 0)
  H.has(result.stdout, 'late feedback')
end)
