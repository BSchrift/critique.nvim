-- The launcher in a real pty (portable: jobstart), with stub `nvim` and `gh` that record how they were called.
local function in_terminal(args, opts)
  opts = opts or {}
  local bin = H.tmp .. '/fake-bin'
  vim.fn.mkdir(bin, 'p')
  vim.fn.writefile({ '#!/bin/sh', 'printf "%s|" "$@" > "' .. H.tmp .. '/nvim-args"' }, bin .. '/nvim')
  vim.fn.writefile({ '#!/bin/sh', 'printf "%s|" "$@" >> "' .. H.tmp .. '/gh-args"', 'printf "\\n" >> "' .. H.tmp .. '/gh-args"',
    'case "$2" in status) exit ' .. (opts.status or 0) .. ';; login) exit ' .. (opts.login or 0) .. ';; esac' }, bin .. '/gh')
  vim.uv.fs_chmod(bin .. '/nvim', 493)
  vim.uv.fs_chmod(bin .. '/gh', 493)
  if opts.no_gh then
    vim.fn.delete(bin .. '/gh')
    for _, tool in ipairs({ 'dirname', 'readlink', 'sed' }) do -- what the launcher needs; never a real gh
      vim.uv.fs_symlink(vim.fn.exepath(tool), bin .. '/' .. tool)
    end
  end
  vim.fn.delete(H.tmp .. '/nvim-args')
  vim.fn.delete(H.tmp .. '/gh-args')
  local out, code = {}, nil
  local path = opts.no_gh and bin or (bin .. ':' .. vim.env.PATH)
  local job = vim.fn.jobstart(vim.list_extend({ opts.launcher or H.bin }, args), {
    pty = true, env = { PATH = path }, clear_env = false,
    on_stdout = function(_, data) vim.list_extend(out, data) end,
    on_exit = function(_, c) code = c end,
  })
  H.ok(job > 0, 'jobstart failed')
  H.wait_for(function() return code ~= nil end, 'the launcher to exit', 20000)
  local read = function(f) return vim.uv.fs_stat(f) and table.concat(vim.fn.readfile(f), '\n') or nil end
  return read(H.tmp .. '/nvim-args'), code, table.concat(out, '\n'), read(H.tmp .. '/gh-args')
end
H.test('in a terminal: handles and no argument open Neovim; typos and commands go to the CLI', function()
  H.eq((in_terminal({ 'cart-fix-1a2b' })), '-c|Critique open cart-fix-1a2b|')
  H.eq((in_terminal({ 'cart-fix-1a2b#3' })), '-c|Critique open cart-fix-1a2b#3|')
  H.eq((in_terminal({ 'cart-fix-1a2b@/some/path' })), '-c|Critique open cart-fix-1a2b@/some/path|')
  H.eq((in_terminal({})), '-c|Critique open |')
  H.has((in_terminal({ 'stauts' })), '-l|' .. H.plugin .. '/lua/critique/cli.lua|stauts|')
  H.has((in_terminal({ 'status' })), '/lua/critique/cli.lua|status|')
end)
